/**
 * 重賞の鍵と開催日から紹介を引く。表に無い鍵、または `since` より前の年のレースなら null。
 */
export function gradedRaceProfile(key: string, date: string): GradedRaceProfile | null {
	const profile = PROFILES[key];
	if (!profile) return null;
	return Number(date.slice(0, 4)) >= profile.since ? profile : null;
}

